-- Gerado por gerar_carga.py | silver.pendencia_evento (todos os eventos, padronizados)
CREATE OR REFRESH STREAMING TABLE pos_venda.silver.pendencia_evento (
  CONSTRAINT pendencia_id_obrigatorio EXPECT (pendencia_id IS NOT NULL) ON VIOLATION DROP ROW,
  CONSTRAINT valor_total_positivo EXPECT (valor_total_pendente > 0) ON VIOLATION DROP ROW,
  CONSTRAINT tipo_evento_valido EXPECT (tipo_evento IN ('NOVA', 'ATUALIZACAO', 'BAIXA')) ON VIOLATION DROP ROW,
  CONSTRAINT cpf_valido EXPECT (NOT dq_cpf_invalido),
  CONSTRAINT email_valido EXPECT (NOT dq_email_invalido)
)
COMMENT 'Silver: todos os eventos de pendencia recebidos (append), com CPF/RG/telefone/CEP/UF padronizados e flags de qualidade (dq_*).'
AS
WITH dig AS (
  SELECT b.*, regexp_replace(b.cliente_cpf, '[^0-9]', '') AS _cpf_dig
  FROM STREAM(bronze_avaliado) b
  WHERE b._motivo_rejeicao IS NULL
),
norm AS (
  SELECT d.*, pos_venda.regras.cpf_valido(d._cpf_dig) AS _cpf_valido FROM dig d
)
SELECT
  pendencia_id,
  data_extracao,
  sistema_origem,
  numero_apolice,
  numero_parcela,
  competencia,
  data_vencimento,
  data_geracao_cobranca,
  dias_atraso,
  faixa_atraso,
  valor_parcela,
  valor_multa,
  valor_juros,
  valor_total_pendente,
  status_cobranca,
  motivo_pendencia,
  tentativas_cobranca,
  data_ultima_tentativa,
  canal_ultimo_contato,
  parcela_afetada_por_endosso,
  ramo,
  status_apolice,
  produto_codigo,
  produto_nome,
  categoria_produto,
  canal_venda,
  data_emissao,
  data_inicio_vigencia,
  data_fim_vigencia_atual,
  dia_vencimento,
  periodicidade_pagamento,
  meses_periodicidade,
  forma_pagamento,
  valor_premio_periodico,
  capital_segurado_principal,
  capital_segurado_total,
  cobertura_principal_codigo,
  cobertura_principal_nome,
  possui_ipta,
  possui_ifpd,
  possui_doencas_graves,
  possui_dit,
  possui_assistencia_funeral,
  qtd_coberturas,
  qtd_endossos,
  numero_ultimo_endosso,
  tipo_ultimo_endosso,
  data_ultimo_endosso,
  qtd_beneficiarios,
  parentesco_beneficiario_principal,
  ponto_venda_codigo,
  ponto_venda_nome,
  ponto_venda_tipo,
  ponto_venda_cidade,
  ponto_venda_uf,
  ponto_venda_regional,
  corretor_id,
  corretor_nome,
  corretor_tipo_pessoa,
  corretor_documento,
  corretor_registro_susep,
  corretor_regional,
  corretor_comissao_pct,
  corretor_status,
  corretor_data_credenciamento,
  cliente_id,
  cliente_nome,
  _cpf_dig AS cliente_cpf,
  cliente_data_nascimento,
  cliente_idade,
  cliente_sexo,
  cliente_estado_civil,
  lower(trim(cliente_email)) AS cliente_email,
  regexp_replace(cliente_celular, '[^0-9]', '') AS cliente_celular,
  regexp_replace(cliente_telefone_fixo, '[^0-9]', '') AS cliente_telefone_fixo,
  upper(regexp_replace(cliente_rg, '[^0-9Xx]', '')) AS cliente_rg,
  cliente_rg_orgao_emissor,
  cliente_rg_uf_emissor,
  cliente_rg_data_emissao,
  cliente_logradouro,
  cliente_numero,
  cliente_complemento,
  cliente_bairro,
  regexp_replace(cliente_cep, '[^0-9]', '') AS cliente_cep,
  cliente_cidade,
  upper(cliente_uf) AS cliente_uf,
  cliente_endereco_completo,
  cliente_renda_faixa,
  cliente_profissao,
  cliente_fumante,
  cliente_data_cadastro,
  tipo_evento, data_baixa, valor_pago,
  NOT _cpf_valido AS dq_cpf_invalido,
  cliente_rg IS NULL AS dq_rg_ausente,
  cliente_celular IS NULL AS dq_celular_ausente,
  cliente_email IS NULL AS dq_email_ausente,
  (cliente_email IS NOT NULL AND NOT (lower(trim(cliente_email)) RLIKE '^[^@ ]+@[^@ ]+[.][^@ ]+$')) AS dq_email_invalido,
  _ingestao_ts, _lote_id, _origem,
  current_timestamp() AS _silver_ts
FROM norm;
