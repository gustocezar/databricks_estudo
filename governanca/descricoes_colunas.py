def descricao(tabela_sem_catalogo, coluna):
    schema, _, tabela = tabela_sem_catalogo.partition(".")
    principal = f"{LEGADO.get(schema, schema)}.{tabela}"
    return POR_TABELA.get((tabela_sem_catalogo, coluna)) or POR_TABELA.get((principal, coluna)) or D.get(coluna)
